export default function Skills() {
  const ref = useRef<HTMLElement>(null);
  const [inView, setInView] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const observer = new IntersectionObserver(
      ([entry]) => { if (entry.isIntersecting) { setInView(true); observer.unobserve(el); } },
      { threshold: 0.05 }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <section
      id="skills"
      ref={ref}
      className="py-24 bg-off-white"
      aria-labelledby="skills-heading"
    >
      <div className="max-w-7xl mx-auto px-6 lg:px-8">
        <div className={`animate-on-scroll ${inView ? 'in-view' : ''}`}>
          <div className="section-overline mb-2" aria-hidden="true" />
          <p className="text-burnt-orange text-xs font-semibold tracking-widest uppercase mb-2">Capabilities</p>
          <h2
            id="skills-heading"
            className="font-serif text-3xl lg:text-4xl font-bold text-charcoal mb-12"
          >
            Skills
          </h2>
        </div>

        <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-6">
          {skills.map((category, index) => (
            <div
              key={category.category}
              className={`card p-6 animate-on-scroll ${inView ? 'in-view' : ''}`}
              style={{ transitionDelay: `${(index + 1) * 80}ms` }}
            >
              {/* Category header */}
              <div className="flex items-center gap-3 mb-5 pb-4 border-b border-light-gray">
                <div className="w-9 h-9 bg-burnt-orange/10 rounded-lg flex items-center justify-center text-burnt-orange flex-shrink-0">
                  {categoryIcons[category.category] ?? (
                    <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">
                      <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M7 7h.01M7 3h5c.512 0 1.024.195 1.414.586l7 7a2 2 0 010 2.828l-7 7a2 2 0 01-2.828 0l-7-7A1.994 1.994 0 013 12V7a4 4 0 014-4z" />
                    </svg>
                  )}
                </div>
                <h3 className="font-serif font-bold text-charcoal">{category.category}</h3>
              </div>

              {/* Skills list */}
              <div className="flex flex-wrap gap-2" role="list" aria-label={`${category.category} skills`}>
                {category.skills.map((skill) => (
                  <span key={skill} className="skill-tag" role="listitem">{skill}</span>
                ))}
              </div>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
